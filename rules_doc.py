def parameters_markdown() -> str:
    lines = ["| Section | Parameter | Value | Defined in |", "|---|---|---|---|"]
    for sec, name, value, where in parameter_rows():
        lines.append(f"| {sec} | {name} | {value} | {where} |")
    return "\n".join(lines)


def _replace_block(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise ValueError("RULES.md is missing the parameters markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}\n{END}{tail}"


def rules_for_app() -> str:
    """RULES.md as the Rules tab shows it: the parameter block always freshly generated from the code."""
    try:
        text = RULES_PATH.read_text(encoding="utf-8")
    except OSError:
        return "# Rules\n\nRULES.md is missing from the app folder.\n\n" + parameters_markdown()
    try:
        return _replace_block(text, parameters_markdown())
    except ValueError:
        return text + "\n\n## Parameters\n\n" + parameters_markdown()


def main(argv: list[str]) -> int:
    text = RULES_PATH.read_text(encoding="utf-8")
    fresh = _replace_block(text, parameters_markdown())
    if "--write" in argv:
        if fresh != text:
            RULES_PATH.write_text(fresh, encoding="utf-8")
            print("RULES.md: parameters section updated from the code.")
        else:
            print("RULES.md: parameters section already matches the code.")
        return 0
    if fresh != text:
        print("RULES.md is out of date: its parameters section does not match the code.\n"
              "Run `python rules_doc.py --write`, then check the rest of RULES.md still describes the logic.")
        return 1
    print("RULES.md parameters match the code.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
